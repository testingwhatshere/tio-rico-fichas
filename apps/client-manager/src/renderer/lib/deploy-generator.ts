export function generateDockerCompose(config: ClientConfig): string {
  const prefix = config.dockerImagePrefix || config.id
  const registry = config.dockerRegistry || 'local'
  return `# ${config.businessName} — Docker Compose
# Generated by Client Manager

version: '3.8'
services:
  api:
    image: ${registry}/${prefix}-api:latest
    build:
      context: ./apps/backend-api
      dockerfile: Dockerfile
    ports:
      - "3000:3000"
    env_file:
      - ./clients/${config.id}/deploy/backend.env
    depends_on:
      - db
    restart: unless-stopped

  db:
    image: postgres:16-alpine
    environment:
      POSTGRES_DB: ${config.id.replace(/-/g, '_')}_db
      POSTGRES_USER: ${config.id.replace(/-/g, '_')}
      POSTGRES_PASSWORD: CHANGE_ME
    volumes:
      - pgdata:/var/lib/postgresql/data
    ports:
      - "5432:5432"
    restart: unless-stopped

volumes:
  pgdata:
`
}

export function generateProvisionScript(config: ClientConfig): string {
  const user = config.vpsUser || config.id.replace(/-/g, '')
  const home = config.homeDirectory || `/opt/${user}`
  const prefix = config.servicePrefix || user
  return `#!/bin/bash
# ${config.businessName} — VPS Provisioning Script
# Generated by Client Manager
# Run as root on Ubuntu 24.04

set -e

# --- Configuration ---
APP_USER="${user}"
APP_HOME="${home}"
SERVICE_PREFIX="${prefix}"
PANEL_URL="${config.gamePanelUrl}"

echo "=== Provisioning ${config.businessName} ==="

# --- Create user ---
if ! id "$APP_USER" &>/dev/null; then
  useradd -m -d "$APP_HOME" -s /bin/bash "$APP_USER"
  echo "User $APP_USER created"
fi

# --- Install dependencies ---
apt-get update -qq
apt-get install -y -qq curl wget unzip docker.io docker-compose-v2

# --- Install Chrome ---
if ! command -v google-chrome &>/dev/null; then
  wget -q https://dl.google.com/linux/direct/google-chrome-stable_current_amd64.deb
  apt-get install -y ./google-chrome-stable_current_amd64.deb
  rm google-chrome-stable_current_amd64.deb
  echo "Chrome installed"
fi

# --- Create directories ---
mkdir -p "$APP_HOME"/{chrome-data,extensions,logs,scripts}
chown -R "$APP_USER:$APP_USER" "$APP_HOME"

# --- Systemd service: Chrome for panel automation ---
cat > /etc/systemd/system/$SERVICE_PREFIX-chrome-panel.service <<EOF
[Unit]
Description=$SERVICE_PREFIX Chrome Panel Automation
After=network.target

[Service]
Type=simple
User=$APP_USER
Environment=DISPLAY=:99
ExecStart=/usr/bin/google-chrome \\
  --no-sandbox \\
  --disable-gpu \\
  --user-data-dir=$APP_HOME/chrome-data \\
  --load-extension=$APP_HOME/extensions/automation-extension \\
  "$PANEL_URL"
Restart=on-failure
RestartSec=10

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
echo "Systemd services created"

echo ""
echo "=== Provisioning complete ==="
echo "Next steps:"
echo "  1. Copy automation extension to $APP_HOME/extensions/"
echo "  2. Configure extension options (API URL, API Key)"
echo "  3. Start: systemctl start $SERVICE_PREFIX-chrome-panel"
echo "  4. Enable: systemctl enable $SERVICE_PREFIX-chrome-panel"
`
}

/**
 * All generators in one call.
 */
export interface GeneratedFiles {
  'backend.env': string
  'chat-app.env': string
  'extension-config.json': string
  'render.yaml': string
  'docker-compose.yml': string
  'provision.sh': string
}

/**
 * Generate all deploy files. Throws if validation fails (blocking errors).
 * Call validateBeforeGeneration() first to check without throwing.
 */
export function generateAllFiles(config: ClientConfig): GeneratedFiles {
  const validation = validateBeforeGeneration(config)
  if (!validation.valid) {
    throw new Error(`Campos requeridos faltantes: ${validation.errors.join(', ')}`)
  }
  return {
    'backend.env': generateBackendEnv(config),
    'chat-app.env': generateChatAppEnv(config),
    'extension-config.json': generateExtensionConfig(config),
    'render.yaml': generateRenderYaml(config),
    'docker-compose.yml': generateDockerCompose(config),
    'provision.sh': generateProvisionScript(config),
  }
}
