import type { ClientConfig } from './types'

// ── Validation ───────────────────────────────────────────────────

/** Fields that BLOCK generation if missing — without these the deploy files are broken */
const BLOCKING_FIELDS: { key: string; label: string; path?: string }[] = [
  { key: 'id', label: 'ID del cliente' },
  { key: 'businessName', label: 'Nombre del negocio' },
  { key: 'apiUrl', label: 'API URL' },
  { key: 'gamePanelUrl', label: 'URL del Panel de Juego' },
  { key: 'botApiKey', label: 'Bot API Key' },
  { key: 'operatorApiKey', label: 'Operator API Key' },
  { key: 'validatorApiKey', label: 'Validator API Key' },
  { key: 'jwtSecret', label: 'JWT Secret' },
  { key: 'databaseUrl', label: 'Database URL', path: 'deployment.databaseUrl' },
]

/** Fields that generate a WARNING but don't block */
const WARNING_FIELDS: { key: string; label: string; path?: string }[] = [
  { key: 'chatWebUrl', label: 'Chat Web URL (afecta CORS)' },
  { key: 'landingUrl', label: 'Landing URL (afecta CORS)' },
  { key: 'cloudinaryUrl', label: 'Cloudinary URL', path: 'deployment.cloudinaryUrl' },
  { key: 'telegramBotToken', label: 'Telegram Bot Token', path: 'deployment.telegramBotToken' },
  { key: 'telegramChatId', label: 'Telegram Chat ID', path: 'deployment.telegramChatId' },
  { key: 'monitoringApiKey', label: 'Monitoring API Key' },
]

function getNestedValue(obj: Record<string, unknown>, path: string): unknown {
  return path.split('.').reduce((acc: unknown, key) => {
    if (acc && typeof acc === 'object') return (acc as Record<string, unknown>)[key]
    return undefined
  }, obj)
}

export interface ValidationResult {
  valid: boolean
  errors: string[]   // Blocking — generation will fail
  warnings: string[] // Advisory — generation proceeds
}

/**
 * Validate a config BEFORE generating deploy files.
 * Returns errors (blocking) and warnings (informational).
 */
export function validateBeforeGeneration(config: ClientConfig): ValidationResult {
  const errors: string[] = []
  const warnings: string[] = []

  for (const field of BLOCKING_FIELDS) {
    const value = field.path
      ? getNestedValue(config as unknown as Record<string, unknown>, field.path)
      : (config as unknown as Record<string, unknown>)[field.key]
    if (!value || (typeof value === 'string' && value.trim() === '')) {
      errors.push(field.label)
    }
  }

  for (const field of WARNING_FIELDS) {
    const value = field.path
      ? getNestedValue(config as unknown as Record<string, unknown>, field.path)
      : (config as unknown as Record<string, unknown>)[field.key]
    if (!value || (typeof value === 'string' && value.trim() === '')) {
      warnings.push(field.label)
    }
  }

  return { valid: errors.length === 0, errors, warnings }
}

// ── Helpers ──────────────────────────────────────────────────────

/**
 * Escape a value for safe inclusion in a .env file (double-quoted).
 * Handles: embedded quotes, dollar signs, backslashes, newlines.
 */
function escapeEnvValue(value: string | undefined | null): string {
  if (!value) return ''
  return value
    .replace(/\\/g, '\\\\')   // backslash first (so we don't double-escape)
    .replace(/"/g, '\\"')      // double quotes
    .replace(/\$/g, '\\$')    // dollar signs (prevent shell expansion)
    .replace(/\n/g, '\\n')    // newlines
    .replace(/\r/g, '\\r')    // carriage returns
}

/** Shorthand: wrap in quotes with escaping */
function envVal(value: string | undefined | null): string {
  return `"${escapeEnvValue(value)}"`
}

